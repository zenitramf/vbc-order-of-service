/**
 * Generates Rick's bundled-skills manifest from the SKILL.md files under
 * `workers/announcement-image-gen/src/skills/<name>/`.
 *
 * Why codegen instead of the `agents:skills` virtual import: that import
 * needs the Agents Vite plugin, but the Rick sidecar deploys with plain
 * `wrangler deploy` (no Vite), so a virtual import would work in dev and
 * break in production. A plain committed TS manifest bundles identically
 * under Vite (local dev) and Wrangler/esbuild (deploy). A vitest sync test
 * (`src/lib/rick-skills-manifest.test.ts`) fails if the two drift.
 *
 * Frontmatter is intentionally restricted to single-line scalars
 * (`name: …`, `description: …`) so this parser stays trivial and exact.
 * Skill resources (references/, scripts/, assets/) are not supported yet —
 * the generator rejects them loudly instead of silently dropping them.
 *
 *   node scripts/generate-rick-skills-manifest.mjs
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const REPO_ROOT = path.resolve(import.meta.dirname, "..");
const SKILLS_DIR = path.join(
  REPO_ROOT,
  "workers/announcement-image-gen/src/skills"
);
const OUTPUT_PATH = path.join(
  REPO_ROOT,
  "workers/announcement-image-gen/src/rick-skills-manifest.ts"
);

const SAFE_SKILL_NAME = /^[A-Za-z0-9][A-Za-z0-9._-]*$/u;

const scalar = (value) => {
  const trimmed = value.trim();

  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"')) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    return trimmed.slice(1, -1);
  }

  return trimmed;
};

export const parseSkillMarkdown = (raw, sourceName) => {
  const match =
    /^---\r?\n(?<frontmatter>[\s\S]*?)\r?\n---\r?\n?(?<body>[\s\S]*)$/u.exec(
      raw
    );

  if (!match?.groups) {
    throw new Error(`${sourceName}: missing --- frontmatter block.`);
  }

  const data = {};

  for (const line of match.groups.frontmatter.split("\n")) {
    if (!line.trim()) {
      continue;
    }

    const field = /^(?<key>[A-Za-z][\w-]*):\s*(?<value>.*)$/u.exec(line);

    if (!field?.groups) {
      throw new Error(
        `${sourceName}: frontmatter must be single-line scalars, got: ${line}`
      );
    }

    data[field.groups.key] = scalar(field.groups.value);
  }

  const { description, name } = data;

  if (!name || !description) {
    throw new Error(`${sourceName}: frontmatter needs name and description.`);
  }

  if (!SAFE_SKILL_NAME.test(name)) {
    throw new Error(`${sourceName}: unsafe skill name “${name}”.`);
  }

  return { body: match.groups.body.trim(), description, name };
};

export const buildRickSkillsManifest = () => {
  const skills = readdirSync(SKILLS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .toSorted((a, b) => a.localeCompare(b))
    .map((directory) => {
      const skillDir = path.join(SKILLS_DIR, directory);
      const files = readdirSync(skillDir);
      const extras = files.filter((file) => file !== "SKILL.md");

      if (extras.length > 0) {
        throw new Error(
          `${directory}: skill resources are not supported yet (found: ${extras.join(", ")}).`
        );
      }

      const rawContent = readFileSync(path.join(skillDir, "SKILL.md"), "utf-8");
      const { body, description, name } = parseSkillMarkdown(
        rawContent,
        `${directory}/SKILL.md`
      );

      return { body, description, name, rawContent, resources: [] };
    });

  const fingerprint = createHash("sha256")
    .update(JSON.stringify(skills))
    .digest("hex");

  return { fingerprint, id: "bundle:rick-skills", skills };
};

const renderManifestModule = (manifest) => `/**
 * GENERATED by scripts/generate-rick-skills-manifest.mjs — do not edit.
 * Source of truth: src/skills/<name>/SKILL.md in this Worker.
 * Regenerate with: pnpm generate:rick-skills
 */
import type { SkillManifest } from "agents/skills";

export const rickSkillsManifest: SkillManifest = ${JSON.stringify(manifest, null, 2)};
`;

const isMain =
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === import.meta.filename;

if (isMain) {
  const manifest = buildRickSkillsManifest();

  writeFileSync(OUTPUT_PATH, renderManifestModule(manifest));
  console.log(
    `Wrote ${path.relative(REPO_ROOT, OUTPUT_PATH)} (${manifest.skills.length} skill(s): ${manifest.skills.map((skill) => skill.name).join(", ")}).`
  );
}
