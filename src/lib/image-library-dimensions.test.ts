import { describe, expect, it } from "vitest";

import { readImageDimensions } from "~/lib/image-library-dimensions";

/** Minimal 1×1 PNG (black pixel). */
const PNG_1X1 = Uint8Array.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49,
  0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x02,
  0x00, 0x00, 0x00, 0x90, 0x77, 0x53, 0xde, 0x00, 0x00, 0x00, 0x0c, 0x49, 0x44,
  0x41, 0x54, 0x08, 0xd7, 0x63, 0xf8, 0xcf, 0xc0, 0x00, 0x00, 0x00, 0x03, 0x00,
  0x01, 0x00, 0x05, 0xfe, 0xd4, 0xef, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e,
  0x44, 0xae, 0x42, 0x60, 0x82,
]);

/**
 * Minimal JPEG with SOF0 declaring 1920×1080.
 * Height 1080 = 0x04 0x38, width 1920 = 0x07 0x80.
 */
const JPEG_1920_1080 = Uint8Array.from([
  0xff, 0xd8, 0xff, 0xc0, 0x00, 0x0b, 0x08, 0x04, 0x38, 0x07, 0x80, 0x01, 0x01,
  0x11, 0x00, 0xff, 0xd9,
]);

describe("readImageDimensions", () => {
  it("reads PNG IHDR width and height", () => {
    expect(readImageDimensions(PNG_1X1.buffer)).toEqual({
      height: 1,
      width: 1,
    });
  });

  it("reads JPEG SOF dimensions", () => {
    expect(readImageDimensions(JPEG_1920_1080.buffer)).toEqual({
      height: 1080,
      width: 1920,
    });
  });

  it("returns null for empty buffers", () => {
    expect(readImageDimensions(new ArrayBuffer(0))).toBeNull();
  });
});
